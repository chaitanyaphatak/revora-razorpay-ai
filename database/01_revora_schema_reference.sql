--          current ReVora Supabase database, which already contains tables
--          and data.
--
-- Source: Non-destructive PostgREST/OpenAPI inspection on 2026-08-27.
-- Notes: Column names, values, and nullable fields were verified. Primary keys,
--        relationships, checks, indexes, and RLS are safe design defaults for a
--        clean recreation; PostgREST inspection cannot prove every original
--        database-side constraint.
